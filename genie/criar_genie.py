"""Creates (or updates) Aurélia's loss-prevention Genie space.

Every example SQL is executed on the warehouse before it goes into the space: a wrong
example teaches Genie to be wrong the same way.

Usage:
    python criar_genie.py --profile field-toolbox --warehouse 9fc569e6e984dcde
    python criar_genie.py --profile field-toolbox --warehouse 9fc569e6e984dcde --space-id <id>
"""

import argparse
import json
import subprocess
import uuid

S = "field_toolbox_catalog.aurelia_speech"

TITULO = "Aurélia · Missing-product claims and fraud"
DESCRICAO = (
    "Ask about consultants' missing-product claims: where and when they spike, "
    "how much was reimbursed, how much was confirmed fraud and which open claims the model says to "
    "investigate first, with what the call said. Aurélia Cosméticos is fictitious and the data is "
    "synthetic."
)

TABELAS = {
    f"{S}.gold_chamados_ciclo": {
        "ciclo": ("21-day sales cycle; cycle 1 starts on May 5, 2025 and cycle 24 is the most recent.", ["cycle", "period"]),
        "transportadora": ("Delivery carrier.", ["carrier", "logistics"]),
        "motivo_declarado": ("Reason the consultant declared: falta_parcial, caixa_violada, nao_recebido, atraso, produto_avariado, outro.", ["reason", "claim type"]),
        "valor_ressarcido": ("Amount refunded to the consultant, in reais (R$).", ["reimbursement", "refund", "credit"]),
        "n_fraudes_confirmadas": ("Claims the investigation concluded were fraud.", ["frauds", "confirmed fraud"]),
        "n_investigados": ("Claims that went through a formal investigation.", ["investigated"]),
    },
    f"{S}.gold_pedidos_ciclo": {
        "n_pedidos": ("Orders in the cycle — the denominator for rates.", ["orders", "volume"]),
    },
    f"{S}.fila_priorizada": {
        "posicao": ("Position in the investigation queue; 1 is the first to open.", ["position", "rank", "priority"]),
        "score_fraude": ("Calibrated fraud probability from the modelo_fraude_chamado model (0 to 1).", ["risk", "fraud probability", "score"]),
        "faixa_risco": ("alta (≥ 0.5), media (0.2 to 0.5) or baixa.", ["band", "risk level"]),
        "resumo_ligacao": ("Summary of the consultant's call, generated by the LLM.", ["summary", "what the call said"]),
        "sinais_relato": ("Signals in the consultant's account: vague details, rushing for the reimbursement, reluctant to send evidence, didn't check on delivery, recurring bad luck, blames third parties.", ["signals", "red flags"]),
    },
    f"{S}.silver_chamados": {
        "resultado": ("Investigation outcome: fraude_confirmada, procedente_* or improcedente. Null if there was no investigation.", ["result", "outcome"]),
        "status": ("aberto, investigado or ressarcido_automatico.", ["status", "state"]),
    },
    f"{S}.gold_call_insights": {
        "tipo_problema": ("Type of problem the LLM identified in the call.", ["problem type"]),
        "summary": ("Call summary.", ["summary"]),
    },
    f"{S}.silver_ligacoes": {},
}

INSTRUCOES = """## PURPOSE
- Answer, in English, questions from Aurélia's Loss Prevention and Customer Service teams about missing-product claims: where they spike, how much they cost, how much is fraud and what to investigate first.
## DEFINITIONS
- 'Claim rate' = 100 × claims / orders, per 100 orders. Aggregate gold_chamados_ciclo and gold_pedidos_ciclo SEPARATELY by the same dimensions (ciclo, cd, transportadora, uf) and only then join: gold_chamados_ciclo has one row per reason and channel, and joining first multiplies the orders.
- 'Route' = transportadora × UF.
- 'Confirmed fraud' = resultado = 'fraude_confirmada'. 'Confirmed fraud rate' = confirmed frauds / investigated claims; it only exists for investigated claims. Never divide frauds by the total number of claims.
- 'Queue' = fila_priorizada: open claims, already in score_fraude order. For 'what to investigate first', order by posicao.
- The most recent cycle (24) is still receiving claims. For trends, use up to cycle 23.
- Calls: silver_ligacoes links call_id to chamado_id; gold_call_insights has the LLM analysis per call_id.
## FORMAT
- Amounts in reais (R$) with a thousands separator; percentages with one decimal place.
- Aurélia is fictitious and the data is synthetic; do not claim these are real numbers from any company.
"""

EXEMPLOS = [
    ("Which routes have the most claims per 100 orders in the last three closed cycles?", f"""
WITH ch AS (
  SELECT transportadora, uf, SUM(n_chamados) AS n_chamados
  FROM {S}.gold_chamados_ciclo WHERE ciclo BETWEEN 21 AND 23 GROUP BY transportadora, uf),
pe AS (
  SELECT transportadora, uf, SUM(n_pedidos) AS n_pedidos
  FROM {S}.gold_pedidos_ciclo WHERE ciclo BETWEEN 21 AND 23 GROUP BY transportadora, uf)
SELECT pe.transportadora, pe.uf, ch.n_chamados, pe.n_pedidos,
       ROUND(100 * ch.n_chamados / pe.n_pedidos, 2) AS chamados_por_100_pedidos
FROM pe JOIN ch ON ch.transportadora = pe.transportadora AND ch.uf = pe.uf
ORDER BY chamados_por_100_pedidos DESC LIMIT 10"""),
    ("How much was reimbursed and how much was confirmed fraud per cycle?", f"""
SELECT ciclo, SUM(n_chamados) AS chamados, ROUND(SUM(valor_ressarcido), 2) AS valor_ressarcido,
       SUM(n_investigados) AS investigados, SUM(n_fraudes_confirmadas) AS fraudes_confirmadas,
       ROUND(SUM(valor_fraude_confirmada), 2) AS valor_fraude_confirmada
FROM {S}.gold_chamados_ciclo GROUP BY ciclo ORDER BY ciclo"""),
    ("What are the top 10 claims in the investigation queue and what did the call say?", f"""
SELECT posicao, chamado_id, score_fraude, faixa_risco, motivo_declarado, valor_reclamado,
       transportadora, uf, resumo_ligacao, sinais_relato
FROM {S}.fila_priorizada ORDER BY posicao LIMIT 10"""),
    ("What is the confirmed fraud rate among investigated claims, by declared reason?", f"""
SELECT motivo_declarado, COUNT(resultado) AS investigados,
       COUNT_IF(resultado = 'fraude_confirmada') AS fraudes_confirmadas,
       ROUND(100 * COUNT_IF(resultado = 'fraude_confirmada') / COUNT(resultado), 1) AS pct_fraude_confirmada
FROM {S}.silver_chamados WHERE resultado IS NOT NULL
GROUP BY motivo_declarado ORDER BY pct_fraude_confirmada DESC"""),
]

PERGUNTAS = [
    "Which routes have the most claims per 100 orders in the last three closed cycles?",
    "Did the Contagem DC see an increase in partial-shortage claims? In which cycles?",
    "How much was reimbursed and how much was confirmed fraud per cycle?",
    "What are the top 10 claims in the investigation queue and what did the call say?",
    "What is the confirmed fraud rate among investigated claims, by declared reason?",
    "How many high-risk claims are open per carrier?",
]


def api(perfil, metodo, caminho, corpo=None):
    cmd = ["databricks", "api", metodo, caminho, "-p", perfil, "-o", "json"]
    if corpo is not None:
        cmd += ["--json", json.dumps(corpo)]
    saida = subprocess.run(cmd, capture_output=True, text=True)
    if saida.returncode:
        raise RuntimeError(saida.stderr or saida.stdout)
    return json.loads(saida.stdout or "{}")


def testar(perfil, warehouse, sql):
    r = api(perfil, "post", "/api/2.0/sql/statements",
            {"warehouse_id": warehouse, "statement": sql, "wait_timeout": "50s"})
    if r["status"]["state"] != "SUCCEEDED":
        raise RuntimeError(f"Example SQL failed: {r['status']}\n{sql}")
    return len(r.get("result", {}).get("data_array", []))


def novo_id():
    return uuid.uuid4().hex


def montar():
    tabelas = []
    for nome, colunas in sorted(TABELAS.items()):
        t = {"identifier": nome}
        if colunas:
            t["column_configs"] = [
                {"column_name": c, "description": [d], "synonyms": s}
                for c, (d, s) in sorted(colunas.items())
            ]
        tabelas.append(t)
    return {
        "version": 2,
        "config": {"sample_questions": sorted(
            [{"id": novo_id(), "question": [q]} for q in PERGUNTAS], key=lambda x: x["id"])},
        "data_sources": {"tables": tabelas},
        "instructions": {
            "text_instructions": [{"id": novo_id(), "content": [l + "\n" for l in INSTRUCOES.strip().split("\n")]}],
            "example_question_sqls": sorted(
                [{"id": novo_id(), "question": [q], "sql": [sql.strip()]} for q, sql in EXEMPLOS],
                key=lambda x: x["id"]),
        },
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--profile", default="field-toolbox")
    ap.add_argument("--warehouse", required=True)
    ap.add_argument("--space-id")
    ap.add_argument("--pasta", default="/Users/ana.sanchez@databricks.com")
    a = ap.parse_args()

    for pergunta, sql in EXEMPLOS:
        print(f"ok ({testar(a.profile, a.warehouse, sql)} rows): {pergunta}")

    corpo = {"title": TITULO, "description": DESCRICAO, "warehouse_id": a.warehouse,
             "serialized_space": json.dumps(montar(), ensure_ascii=False)}
    if a.space_id:
        r = api(a.profile, "patch", f"/api/2.0/genie/spaces/{a.space_id}", corpo)
    else:
        r = api(a.profile, "post", "/api/2.0/genie/spaces", {**corpo, "parent_path": a.pasta})
    print(f"space: {r.get('space_id')} · {r.get('title')}")


if __name__ == "__main__":
    main()
